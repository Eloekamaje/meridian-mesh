"""Port de persistance du pilotage. Les services applicatifs ne connaissent que ce contrat."""
from __future__ import annotations

from datetime import date
from typing import Any, Protocol


class PlanificationStore(Protocol):
    def equipes(self, conn, tenant: str) -> list[dict]: ...
    def capacites(self, conn, tenant: str, equipe_id: str | None = None,
                  debut: date | None = None, fin: date | None = None) -> list[dict]: ...
    def absences(self, conn, tenant: str, equipe_id: str | None = None,
                 debut: date | None = None, fin: date | None = None) -> list[dict]: ...
    def allocations(self, conn, tenant: str, equipe_id: str | None = None) -> list[dict]: ...
    def temps(self, conn, tenant: str, equipe_id: str | None = None,
              debut: date | None = None, fin: date | None = None) -> list[dict]: ...
    def taux(self, conn, tenant: str, equipe_id: str | None = None) -> list[dict]: ...
    def elements(self, conn, tenant: str, *, equipe_id: str | None = None,
                 debut: date | None = None, fin: date | None = None, actifs: bool = True) -> list[dict]: ...
    def elements_historique(self, conn, tenant: str, equipe_id: str | None = None) -> list[dict]: ...
    def cycles(self, conn, tenant: str, equipe_id: str | None = None,
               termines: bool | None = None) -> list[dict]: ...
    def dependances(self, conn, tenant: str) -> list[dict]: ...
    def plans(self, conn, tenant: str, equipe_id: str | None = None) -> list[dict]: ...
    def plan(self, conn, tenant: str, plan_id: str) -> dict | None: ...
    def previsions(self, conn, tenant: str, equipe_id: str | None = None) -> list[dict]: ...
    def budgets(self, conn, tenant: str, initiative_id: str | None = None) -> list[dict]: ...
    def couts(self, conn, tenant: str, budget_id: str | None = None) -> list[dict]: ...
    def valeurs(self, conn, tenant: str, initiative_id: str | None = None) -> list[dict]: ...
    def roles(self, conn, tenant: str, acteur: str | None = None) -> list[dict]: ...
    def affecter_role(self, conn, tenant: str, affectation: dict) -> str: ...
    def membres(self, conn, tenant: str, equipe_id: str | None = None) -> list[dict]: ...
    def competences(self, conn, tenant: str, equipe_id: str | None = None) -> list[dict]: ...
    def enregistrer_equipe(self, conn, tenant: str, equipe: dict) -> str: ...
    def enregistrer_element(self, conn, tenant: str, element: dict) -> str: ...
    def desactiver_absents(self, conn, tenant: str, source_id: str, externes: list[str]) -> int: ...
    def enregistrer_cycle(self, conn, tenant: str, cycle: dict) -> str: ...
    def enregistrer_release(self, conn, tenant: str, release: dict) -> str: ...
    def enregistrer_dependance(self, conn, tenant: str, dependance: dict) -> str: ...
    def enregistrer_capacite(self, conn, tenant: str, capacite: dict) -> str: ...
    def enregistrer_absence(self, conn, tenant: str, absence: dict) -> str: ...
    def enregistrer_allocation(self, conn, tenant: str, allocation: dict) -> str: ...
    def enregistrer_temps(self, conn, tenant: str, temps: dict) -> str: ...
    def enregistrer_taux(self, conn, tenant: str, taux: dict) -> str: ...
    def enregistrer_membre(self, conn, tenant: str, membre: dict) -> str: ...
    def enregistrer_competence(self, conn, tenant: str, competence: dict) -> str: ...
    def enregistrer_prevision(self, conn, tenant: str, prevision: dict) -> str: ...
    def enregistrer_plan(self, conn, tenant: str, plan: dict, lignes: list[dict] | None = None) -> str: ...
    def enregistrer_budget(self, conn, tenant: str, budget: dict) -> str: ...
    def enregistrer_cout(self, conn, tenant: str, cout: dict) -> str: ...
    def creer_sync_run(self, conn, tenant: str, source_id: str) -> str: ...
    def terminer_sync_run(self, conn, tenant: str, run_id: str, **champs) -> None: ...
    def lire_source(self, conn, tenant: str, source_id: str) -> dict | None: ...
    def lister_sources(self, conn, tenant: str) -> list[dict]: ...
    def maj_source(self, conn, tenant: str, source_id: str, **champs) -> None: ...
